test('rejects invalid time without silently losing a draft', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Задача N', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Начало', { exact: true }).fill('20:00')
  await dialog.getByRole('button', { name: 'Закрыть панель' }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('alert')).toContainText('Окончание должно быть позже начала')
  await dialog.getByLabel('Окончание', { exact: true }).fill('21:00')
  await dialog.getByRole('button', { name: 'Закрыть панель' }).click()
  await expect(dialog).not.toBeVisible()
})
