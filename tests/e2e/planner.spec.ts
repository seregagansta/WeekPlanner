import { test, expect } from '@playwright/test'
test('create, autosave, reload, complete, drag, filter and delete a task', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('.task-card')).toHaveCount(13)
  await page.getByRole('button', { name: 'Задача N', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Задача', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('Название', { exact: true }).fill('Проверка прототипа')
  await dialog.getByLabel('Описание', { exact: true }).fill('Автосохранение работает')
  await dialog.getByLabel('Заметки', { exact: true }).fill('Важная заметка')
  await dialog.getByLabel('Начало', { exact: true }).fill('17:00')
  await dialog.getByLabel('Окончание', { exact: true }).fill('18:30')
  await dialog.getByRole('button', { name: 'Закрыть панель' }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  const card = page
    .locator('.task-card')
    .filter({ has: page.getByRole('button', { name: 'Проверка прототипа', exact: true }) })
  await expect(card).toContainText('17:00 – 18:30')
  await card.hover()
  await card.getByRole('button', { name: 'Выполнить: Проверка прототипа', exact: true }).click()
  await expect(card).toHaveClass(/completed/)
  const handle = card.getByRole('button', { name: 'Перенести: Проверка прототипа' })
  const source = await handle.boundingBox()
  const target = await page.locator('.day-column').last().boundingBox()
  if (!source || !target) throw new Error('Missing drag positions')
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, source.y + source.height / 2, { steps: 15 })
  await page.mouse.up()
  await expect(
    page
      .locator('.day-column')
      .last()
      .getByRole('button', { name: 'Проверка прототипа', exact: true }),
  ).toBeVisible()
  await page.getByLabel('Поиск задач', { exact: true }).fill('Важная заметка')
  await expect(page.locator('.task-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Проверка прототипа', exact: true }).click()
  await expect(dialog.getByLabel('Описание', { exact: true })).toHaveValue(
    'Автосохранение работает',
  )
  await dialog.getByRole('button', { name: 'Удалить задачу', exact: true }).click()
  await dialog.getByRole('button', { name: 'Да, удалить', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.task-card')).toHaveCount(0)
  expect(errors).toEqual([])
})
